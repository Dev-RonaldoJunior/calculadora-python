#=====        Função de Adição        =====
def somar(n1, n2):
    return n1 + n2

#=====        Função de Subtração        =====
def subtrair(n1, n2):
    return n1 - n2

#=====        Função de Multiplicação        =====
def multiplicar(n1, n2):
    return n1 * n2

#=====        Função de Divisão        =====
def dividir(n1, n2):
    return n1 / n2

#=====        Função de Porcentagem        =====
def porcentagem(n1, n2):
    return n1 * n2 / 100