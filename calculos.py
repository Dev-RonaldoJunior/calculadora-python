#==============================Função de adição==============================
def somar(n1, n2):
    return n1 + n2

#==============================Função de subtração==============================
def subtrair(n1, n2):
    return n1 - n2

#==============================Função de multiplicação==============================
def multiplicar(n1, n2):
    return n1 * n2

#==============================Função de divisão==============================
def dividir(n1, n2):
    return n1 / n2
